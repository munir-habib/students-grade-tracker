#!/usr/bin/env node
// onboard-student.mjs
//
// Standalone, zero-dependency dev tool. NOT part of the React app build.
//
// Generates a one-off onboarding SQL script for a SINGLE student, from a
// SINGLE grade-tracking workbook (.xlsx).
//
// Design choices, on purpose:
//   - The target user_id is looked up at SQL-run time from auth.users.email,
//     not hardcoded — the student must already have signed into the app at
//     least once (that's what creates her auth.users row). If she hasn't,
//     the script raises a clear exception and inserts nothing.
//   - The generated script is idempotent per course, not just per term: a
//     term with the given name is reused if it already exists (instead of
//     always inserting a fresh one), and each course is only inserted if no
//     course with that name already exists under that term for that user.
//     This matters for a term that exists but is missing some/all of its
//     courses (e.g. a previous run that partially failed) — re-running fills
//     in exactly the missing courses instead of skipping everything because
//     the term alone already exists.
//   - Reusable for onboarding other real students later: same script, just
//     pass a different --email/--file/--term.
//
// Usage:
//   node supabase/seed/onboard-student.mjs \
//     --file "C:\path\to\Some Student Grade Tracker.xlsx" \
//     --email "student@example.com" \
//     --term "Spring 2026" \
//     [--sort 0] [--mode syllabus|notes] [--credits 3] [--out path.sql]
//
// mode defaults to 'syllabus' (column F = numeric points-possible-per-syllabus).
// Use --mode notes if the workbook instead has free-text notes in column F.
//
// Run the resulting .sql file in the Supabase SQL Editor (or `supabase db
// execute -f <file>`) — it runs as a superuser there, so it can read
// auth.users and write across every student's rows despite RLS.
//
// Boundaries: this script only writes the --out SQL file. It never touches
// src/, supabase/migrations/, or supabase/functions/, and it never runs npm
// install or talks to the database itself.

import fs from 'node:fs';
import path from 'node:path';

import { extractWorkbook, sqlStr, sqlNum, uuid } from './xlsx-lite.mjs';

const DEFAULT_CREDITS = 3;

function parseArgs(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (!a.startsWith('--')) continue;
    const key = a.slice(2);
    const next = argv[i + 1];
    args[key] = next;
    i++;
  }
  return args;
}

function slugify(s) {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
}

function main() {
  const args = parseArgs(process.argv.slice(2));

  const file = args.file;
  const email = args.email;
  const termName = args.term;
  const sortOrder = args.sort !== undefined ? Number(args.sort) : 0;
  const mode = args.mode || 'syllabus';
  const credits = args.credits !== undefined ? Number(args.credits) : DEFAULT_CREDITS;
  const outPath =
    args.out || path.join('supabase', 'seed', `onboard-${slugify(email || 'student')}-${slugify(termName || 'term')}.sql`);

  if (!file || !email || !termName) {
    console.error('Usage: node supabase/seed/onboard-student.mjs --file <path.xlsx> --email <email> --term <name> [--sort 0] [--mode syllabus|notes] [--credits 3] [--out path.sql]');
    process.exit(1);
  }
  if (!fs.existsSync(file)) {
    console.error(`ERROR: source workbook not found: ${file}`);
    process.exit(1);
  }
  if (mode !== 'syllabus' && mode !== 'notes') {
    console.error(`ERROR: --mode must be "syllabus" or "notes", got "${mode}"`);
    process.exit(1);
  }

  const courses = extractWorkbook(file, mode);

  const sqlLines = [];
  sqlLines.push('-- ============================================================================');
  sqlLines.push(`-- Student onboarding seed — generated by supabase/seed/onboard-student.mjs`);
  sqlLines.push('-- DO NOT EDIT BY HAND. Re-run the generator to regenerate this file.');
  sqlLines.push('--');
  sqlLines.push(`-- Generated: ${new Date().toISOString()}`);
  sqlLines.push(`-- Source workbook: ${path.basename(file)}`);
  sqlLines.push(`-- Target account: ${email} (looked up dynamically from auth.users at run time —`);
  sqlLines.push('-- she must have signed into the app at least once before this script is run).');
  sqlLines.push('--');
  sqlLines.push('-- Idempotent per course: the term is reused if it already exists for this user,');
  sqlLines.push('-- and each course is only inserted if no course with that name already exists');
  sqlLines.push('-- under that term — so a term left over from a partial/failed run gets its');
  sqlLines.push('-- missing courses filled in instead of everything being skipped.');
  sqlLines.push('--');
  sqlLines.push('-- ASSUMPTION TO DOUBLE CHECK: the workbook states no explicit credit hours, so');
  sqlLines.push(`-- every course below is seeded with a placeholder credits = ${credits}.`);
  sqlLines.push('-- Please correct real credit values per course after import.');
  sqlLines.push('-- ============================================================================');
  sqlLines.push('');
  sqlLines.push('do $$');
  sqlLines.push('declare');
  sqlLines.push('  v_user_id uuid;');
  sqlLines.push('  v_term_id uuid;');
  sqlLines.push('  v_course_id uuid;');
  sqlLines.push('  v_inserted_count int := 0;');
  sqlLines.push('  v_skipped_count int := 0;');
  sqlLines.push('begin');
  sqlLines.push(`  select id into v_user_id from auth.users where email = ${sqlStr(email)};`);
  sqlLines.push('  if v_user_id is null then');
  sqlLines.push(
    `    raise exception 'No auth.users row for email %. Ask the student to sign in to the app at least once, then re-run this script.', ${sqlStr(email)};`
  );
  sqlLines.push('  end if;');
  sqlLines.push('');
  sqlLines.push(`  -- Term: ${termName} (from "${path.basename(file)}") — reuse if it already exists.`);
  sqlLines.push(
    `  select id into v_term_id from public.terms where user_id = v_user_id and name = ${sqlStr(termName)};`
  );
  sqlLines.push('  if v_term_id is null then');
  sqlLines.push('    v_term_id := gen_random_uuid();');
  sqlLines.push(
    `    insert into public.terms (id, user_id, name, sort_order) values (v_term_id, v_user_id, ${sqlStr(termName)}, ${sqlNum(sortOrder)});`
  );
  sqlLines.push('  end if;');
  sqlLines.push('');

  const summary = [];

  for (const course of courses) {
    summary.push({ courseName: course.courseName, rowCount: course.assessments.length });

    sqlLines.push(`  -- Course: ${course.courseName}`);
    sqlLines.push(
      `  if exists (select 1 from public.courses where user_id = v_user_id and term_id = v_term_id and name = ${sqlStr(course.courseName)}) then`
    );
    sqlLines.push(
      `    raise notice 'Course % already exists for % in % — skipping.', ${sqlStr(course.courseName)}, ${sqlStr(email)}, ${sqlStr(termName)};`
    );
    sqlLines.push('    v_skipped_count := v_skipped_count + 1;');
    sqlLines.push('  else');
    sqlLines.push('    v_course_id := gen_random_uuid();');
    sqlLines.push(
      `    insert into public.courses (id, user_id, term_id, name, credits, calc_mode) values (v_course_id, v_user_id, v_term_id, ${sqlStr(course.courseName)}, ${sqlNum(credits)}, 'points');`
    );

    if (course.assessments.length === 0) {
      sqlLines.push(`    -- (no assessment rows parsed for "${course.courseName}" — nothing to seed)`);
    } else {
      const categoryIds = new Map();
      for (const categoryName of course.categories) {
        const categoryId = uuid();
        categoryIds.set(categoryName, categoryId);
        const dropCount = categoryName === 'Quiz' ? course.dropLowestQuizzes : 0;
        sqlLines.push(
          `    insert into public.categories (id, course_id, name, weight_pct, drop_lowest_count) values (${sqlStr(
            categoryId
          )}, v_course_id, ${sqlStr(categoryName)}, null, ${sqlNum(dropCount)});`
        );
      }

      for (const a of course.assessments) {
        const categoryId = categoryIds.get(a.category);
        sqlLines.push(
          `    insert into public.assessments (id, category_id, name, date, status, points_possible_syllabus, points_possible_actual, points_earned, percent_direct, comment) values (${sqlStr(
            uuid()
          )}, ${sqlStr(categoryId)}, ${sqlStr(a.name)}, null, ${sqlStr(a.status)}, ${sqlNum(
            a.pointsPossibleSyllabus
          )}, ${sqlNum(a.pointsPossibleActual)}, ${sqlNum(a.pointsEarned)}, null, ${sqlStr(a.comment)});`
        );
      }
    }

    sqlLines.push('    v_inserted_count := v_inserted_count + 1;');
    sqlLines.push('  end if;');
    sqlLines.push('');
  }

  sqlLines.push(
    `  raise notice 'Onboarded % into term %: % course(s) inserted, % already present.', ${sqlStr(email)}, ${sqlStr(termName)}, v_inserted_count, v_skipped_count;`
  );
  sqlLines.push('end $$;');
  sqlLines.push('');

  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, sqlLines.join('\n'), 'utf8');

  console.log('\nGenerated', outPath);
  console.log('\nPer-course row counts:');
  let total = 0;
  for (const row of summary) {
    total += row.rowCount;
    console.log(`  ${row.courseName.padEnd(14)} -> ${row.rowCount} assessment rows`);
  }
  console.log(`\nTotal: ${summary.length} courses, ${total} assessment rows.`);
  console.log(`\nRun this in the Supabase SQL Editor once ${email} has signed into the app at least once.`);
}

main();
